"""Generate MITRE ATT&CK coverage from rule tags: a Navigator layer and a markdown summary."""
from __future__ import annotations

import json
from collections import defaultdict

from tools.common import BUILD_DIR, DOCS_DIR, attack_tags, load_raw, rule_files

# Update to match the ATT&CK version your Navigator instance uses.
ATTACK_VERSION = "17"

TACTIC_ORDER = [
    "reconnaissance", "resource-development", "initial-access", "execution", "persistence",
    "privilege-escalation", "defense-evasion", "credential-access", "discovery",
    "lateral-movement", "collection", "command-and-control", "exfiltration", "impact",
]


def technique_url(tid: str) -> str:
    return "https://attack.mitre.org/techniques/" + tid.replace(".", "/") + "/"


def main() -> int:
    by_technique: dict[str, list[str]] = defaultdict(list)
    by_tactic: dict[str, list[str]] = defaultdict(list)
    for path in rule_files():
        raw = load_raw(path)
        tactics, techniques = attack_tags(raw)
        for t in techniques:
            by_technique[t].append(path.stem)
        for t in tactics:
            by_tactic[t].append(path.stem)

    layer = {
        "name": "detection-as-code coverage",
        "versions": {"attack": ATTACK_VERSION, "navigator": "5.1.0", "layer": "4.5"},
        "domain": "enterprise-attack",
        "description": "Techniques covered by at least one rule in this repository.",
        "gradient": {"colors": ["#cfe8ff", "#1f77d0"], "minValue": 0, "maxValue": 3},
        "techniques": [
            {"techniqueID": tid, "score": len(rules), "comment": ", ".join(rules)}
            for tid, rules in sorted(by_technique.items())
        ],
    }
    BUILD_DIR.mkdir(exist_ok=True)
    (BUILD_DIR / "attack-layer.json").write_text(json.dumps(layer, indent=2) + "\n", encoding="utf-8")

    n_rules = len(rule_files())
    ordered = [t for t in TACTIC_ORDER if t in by_tactic] + sorted(set(by_tactic) - set(TACTIC_ORDER))
    lines = [
        "# ATT&CK coverage",
        "",
        "_Generated by `python -m tools.coverage`. Do not edit by hand. "
        "Import `build/attack-layer.json` into ATT&CK Navigator for the heatmap._",
        "",
        f"**{n_rules} rules · {len(by_technique)} techniques · {len(by_tactic)} tactics**",
        "",
        "## By tactic",
        "",
        "| Tactic | Rules |",
        "|---|---|",
    ]
    for tac in ordered:
        lines.append(f"| {tac} | {len(by_tactic[tac])} |")
    lines += ["", "## By technique", "", "| Technique | Rules |", "|---|---|"]
    for tid, rules in sorted(by_technique.items()):
        lines.append(f"| [{tid}]({technique_url(tid)}) | {', '.join(f'`{r}`' for r in rules)} |")
    DOCS_DIR.mkdir(exist_ok=True)
    (DOCS_DIR / "coverage.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(lines[4])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
