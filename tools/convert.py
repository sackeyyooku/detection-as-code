"""Compile every Sigma rule into backend queries and write a conversion matrix.

Targets
  splunk        SPL, using the pySigma Windows pipeline + pipelines/splunk_env.yml
  kql-defender  KQL for Microsoft Defender XDR advanced hunting (DeviceProcessEvents etc.)

Rules a target cannot express (unsupported logsource / unmapped field) are recorded in the
matrix instead of failing the build; any other error fails loudly.
"""
from __future__ import annotations

from pathlib import Path

from sigma.backends.kusto import KustoBackend
from sigma.backends.splunk import SplunkBackend
from sigma.collection import SigmaCollection
from sigma.exceptions import SigmaError
from sigma.pipelines.microsoftxdr import microsoft_xdr_pipeline
from sigma.pipelines.splunk import splunk_windows_pipeline
from sigma.processing.pipeline import ProcessingPipeline

from tools.common import BUILD_DIR, DOCS_DIR, PIPELINES_DIR, load_collection, load_raw, rule_files


def _splunk_backend() -> SplunkBackend:
    env = ProcessingPipeline.from_yaml((PIPELINES_DIR / "splunk_env.yml").read_text())
    return SplunkBackend(splunk_windows_pipeline() + env)


def _kql_defender_backend() -> KustoBackend:
    return KustoBackend(microsoft_xdr_pipeline())


TARGETS = {
    "splunk": ("spl", _splunk_backend),
    "kql-defender": ("kql", _kql_defender_backend),
}


def _reason(err: SigmaError) -> str:
    text = str(err).split("\n")[0]
    if "Unable to determine table name" in text:
        return "unsupported logsource"
    if "Invalid SigmaDetectionItem field name" in text:
        return "unmapped field"
    return text[:70]


def main() -> int:
    results: dict[str, dict[str, str]] = {}
    for target, (ext, make_backend) in TARGETS.items():
        out_dir = BUILD_DIR / target
        out_dir.mkdir(parents=True, exist_ok=True)
        for path in rule_files():
            row = results.setdefault(path.stem, {})
            try:
                queries = make_backend().convert(load_collection(path))
            except SigmaError as err:
                row[target] = _reason(err)
                continue
            (out_dir / f"{path.stem}.{ext}").write_text(queries[0] + "\n", encoding="utf-8")
            row[target] = "ok"

    # One savedsearches.conf for Splunk: the artefact a deploy stage would ship.
    merged = SigmaCollection.merge([load_collection(p) for p in rule_files()])
    conf = _splunk_backend().convert(merged, output_format="savedsearches")
    (BUILD_DIR / "splunk" / "savedsearches.conf").write_text(conf, encoding="utf-8")

    lines = [
        "# Conversion matrix",
        "",
        "_Generated by `python -m tools.convert`. Do not edit by hand._",
        "",
        "| Rule | Level | Splunk SPL | KQL (Defender XDR) |",
        "|---|---|---|---|",
    ]
    for path in rule_files():
        level = load_raw(path)["level"]
        row = results[path.stem]
        cells = [("✅" if row[t] == "ok" else f"❌ {row[t]}") for t in TARGETS]
        lines.append(f"| `{path.stem}` | {level} | {cells[0]} | {cells[1]} |")
    total = len(results)
    for t in TARGETS:
        ok = sum(1 for r in results.values() if r[t] == "ok")
        lines.append(f"\n**{t}:** {ok}/{total} rules compiled")
    DOCS_DIR.mkdir(exist_ok=True)
    (DOCS_DIR / "conversion-matrix.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[-len(TARGETS):]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
